#!/usr/bin/env python3
"""Collect every stickers/<sheet>/manifest.json into stickers/index.js
so index.html works even when opened directly from disk (no fetch needed).

Sheet labels / default materials come from stickers/sheets.json.
A label is a plain string or one per language:
  {"gems": {"label": {"en": "Gems", "zh": "宝石"}, "material": "crystal"}}
"""
import json, os, glob
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "stickers")
cfg_path = os.path.join(root, "sheets.json")
cfg = json.load(open(cfg_path)) if os.path.exists(cfg_path) else {}
sheets = []
for mf in sorted(glob.glob(os.path.join(root, "*", "manifest.json"))):
    sid = os.path.basename(os.path.dirname(mf))
    items = json.load(open(mf))
    meta = cfg.get(sid, {})
    sheets.append({
        "id": sid,
        "label": meta.get("label", sid),
        "material": meta.get("material", "paper"),
        "items": [{"file": f"stickers/{sid}/{it['file']}", "w": it["w"], "h": it["h"],
                   **({"mat": it["mat"]} if it.get("mat") else {}), **({"src": it["src"]} if it.get("src") else {})} for it in items],
    })
# keep the order given in sheets.json first
order = list(cfg.keys())
sheets.sort(key=lambda s: order.index(s["id"]) if s["id"] in order else 999)
with open(os.path.join(root, "index.js"), "w") as f:
    f.write("// generated by tools/build_index.py — do not edit by hand\n")
    f.write("window.STICKER_SHEETS = " + json.dumps(sheets, ensure_ascii=False, indent=1) + ";\n")
print("wrote stickers/index.js with", [(s["id"], len(s["items"])) for s in sheets])
